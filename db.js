const sqlite = require('sqlite3');
const db = new sqlite.Database('construction.db');

const createProjectTable = `CREATE TABLE IF NOT EXISTS PROJECT (
ID INTEGER PRIMARY KEY AUTOINCREMENT, 
PROJECTNAME TEXT NOT NULL,
SITELOCATION TEXT NOT NULL,
REGION TEXT NOT NULL,
PRIMARYLANGUAGE TEXT NOT NULL,
PROJECTDESCRIPTION TEXT NOT NULL,
MATERIALCOST REAL DEFAULT 0,
LABORCOST REAL DEFAULT 0,
EQUIPMENTCOST REAL DEFAULT 0,
PERMITCOST REAL DEFAULT 0,
LOGISTICSCOST REAL DEFAULT 0,
CURRENCYCODE TEXT DEFAULT 'N/A'
)`;

const createUserTable = `CREATE TABLE IF NOT EXISTS USER (
    ID INTEGER PRIMARY KEY AUTOINCREMENT, 
    NAME TEXT NOT NULL,
    EMAIL TEXT UNIQUE NOT NULL,
    ROLE TEXT NOT NULL,
    PASSWORD TEXT NOT NULL
)`;

const createTaskTable = `CREATE TABLE IF NOT EXISTS TASK (
    ID INTEGER PRIMARY KEY AUTOINCREMENT,
    PROJECTID INTEGER NOT NULL,
    USERID INTEGER NOT NULL,
    TASKNAME TEXT NOT NULL,
    DESCRIPTION TEXT,
    STATUS TEXT DEFAULT 'Pending',
    DUE_DATE TEXT,
    FOREIGN KEY(PROJECTID) REFERENCES PROJECT(ID),
    FOREIGN KEY(USERID) REFERENCES USER(ID)
)`;

const createMaterialRequestTable = `CREATE TABLE IF NOT EXISTS MATERIAL_REQUEST (
    ID INTEGER PRIMARY KEY AUTOINCREMENT,
    PROJECTID INTEGER NOT NULL,
    MATERIALNAME TEXT NOT NULL,
    QUANTITY REAL NOT NULL,
    STATUS TEXT DEFAULT 'Pending',
    REQUEST_DATE TEXT DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(PROJECTID) REFERENCES PROJECT(ID)
)`;

module.exports = {
    db,
    createProjectTable,
    createUserTable,
    createTaskTable,
    createMaterialRequestTable
};
